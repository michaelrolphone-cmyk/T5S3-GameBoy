#include <cassert>
#include <cstdint>
#include "usb_hid_report.h"

int main() {
  const uint8_t gamepad[] = {
      0x05,0x01,0x09,0x05,0xA1,0x01,
      0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x0A,
      0x05,0x09,0x19,0x01,0x29,0x0A,0x81,0x02,
      0x75,0x06,0x95,0x01,0x81,0x03,
      0x05,0x01,0x25,0x07,0x75,0x04,0x95,0x01,
      0x09,0x39,0x81,0x42,
      0x75,0x04,0x95,0x01,0x81,0x03,0xC0};
  UsbHidGamepadReport layout;
  assert(usb_hid_parse_gamepad_descriptor(gamepad, sizeof(gamepad), layout));
  assert(layout.report_id == 0 && layout.report_bits == 24);
  UsbHidGamepadState state;
  const uint8_t right_b_r[] = {0x21, 0x00, 0x02};
  assert(usb_hid_decode_gamepad(layout, right_b_r, sizeof(right_b_r), state));
  assert(state.right && !state.left && state.b && state.r && !state.a);
  const uint8_t neutral[] = {0, 0, 8}; // HID hat null/out-of-range.
  assert(usb_hid_decode_gamepad(layout, neutral, sizeof(neutral), state));
  assert(!state.up && !state.right && !state.down && !state.left);
  assert(!state.b && !state.r);
  assert(!usb_hid_decode_gamepad(layout, neutral, 2, state));
  const uint8_t rid_gamepad[] = {
      0x05,0x01,0x09,0x05,0xA1,0x01,0x85,0x02,
      0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x0A,
      0x05,0x09,0x19,0x01,0x29,0x0A,0x81,0x02,
      0x75,0x06,0x95,0x01,0x81,0x03,
      0x05,0x01,0x25,0x07,0x75,0x04,0x95,0x01,
      0x09,0x39,0x81,0x42,
      0x75,0x04,0x95,0x01,0x81,0x03,0xC0};
  assert(usb_hid_parse_gamepad_descriptor(rid_gamepad, sizeof(rid_gamepad), layout));
  assert(layout.report_id == 2);
  const uint8_t right_with_id[] = {2, 0x21, 0, 2};
  assert(usb_hid_decode_gamepad(layout, right_with_id, sizeof(right_with_id), state));
  assert(state.right && state.b);
  const uint8_t wrong_id[] = {3, 0x21, 0, 2};
  assert(!usb_hid_decode_gamepad(layout, wrong_id, sizeof(wrong_id), state));
  const uint8_t axes[] = {
      0x05,0x01,0x09,0x04,0xA1,0x01,0x15,0x00,0x26,0xFF,0x00,
      0x75,0x08,0x95,0x02,0x09,0x30,0x09,0x31,0x81,0x02,0xC0};
  assert(usb_hid_parse_gamepad_descriptor(axes, sizeof(axes), layout));
  const uint8_t left_down[] = {0,255};
  assert(usb_hid_decode_gamepad(layout, left_down, sizeof(left_down), state));
  assert(state.left && state.down && !state.right && !state.up);
  const uint8_t keyboard[] = {0x05,0x01,0x09,0x06,0xA1,0x01,
      0x75,0x08,0x95,0x01,0x09,0x30,0x81,0x02,0xC0};
  assert(!usb_hid_parse_gamepad_descriptor(keyboard, sizeof(keyboard), layout));
  assert(!usb_hid_parse_gamepad_descriptor(gamepad, 4, layout));
  assert(!usb_hid_parse_gamepad_descriptor(nullptr, 0, layout));
}
